"""Writes src/xmojo/html_entities.mojo from Python's html.entities.html5 (the WHATWG named character
references): one line per entity, `name hex[,hex]`, XML's five predefined entities left out."""
import html.entities, pathlib

XML = {"amp", "lt", "gt", "quot", "apos"}
rows = sorted((k[:-1], ",".join("%x" % ord(c) for c in v))
              for k, v in html.entities.html5.items() if k.endswith(";") and k[:-1] not in XML)
data = "\n".join("%s %s" % r for r in rows)
out = pathlib.Path(__file__).resolve().parent.parent / "src/xmojo/html_entities.mojo"
out.write_text('''# Copyright 2026 amarbaro.org. Licensed under the Apache License, Version 2.0 (this code).
# The entity data: Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft). Portions of the HTML
# Standard incorporated into source code are licensed under the BSD 3-Clause License
# (https://github.com/whatwg/html/blob/main/LICENSE); see NOTICE for its full text.
#
# Generated by tools/gen_entities.py from Python's html.entities.html5, the WHATWG HTML Standard's
# named character references. Do not edit. %d entries, one per line: name, then code points in hex.
from .tokenizer import _parse_uint

comptime _DATA: StaticString = """%s"""


def html_entities() raises -> Dict[String, String]:
    """HTML's named character references (`nbsp` -> U+00A0, ...) as an `entities` map for
    `parse` and `from_xml`. Builds the map on each call: build it once and reuse it."""
    var out = Dict[String, String]()
    for line in _DATA.split("\\n"):
        var sp = line.find(" ")
        var value = String()
        for h in line[byte = sp + 1 :].split(","):
            value += String(Codepoint.from_u32(_parse_uint(h.as_bytes(), 16)).value())
        out[String(line[byte=0:sp])] = value^
    return out^
''' % (len(rows), data))
print("wrote", out, len(rows), "entities")
